/* ================= OPEN DETAIL ================= */

function openDetail(id) {

    const modal = document.getElementById("detailModal");
    const title = document.getElementById("modalTitle");
    const content = document.getElementById("modalContent");

    // Pastikan elemen modal ada
    if (!modal || !title || !content) {
        console.error("Modal tidak ditemukan. Pastikan HTML memiliki #detailModal, #modalTitle, dan #modalContent.");
        return;
    }

    const data = details[id];

    // Data tidak ditemukan
    if (!data) {
        console.error("Detail tidak ditemukan:", id);
        return;
    }

    // Judul
    title.textContent = data.title;

    // Isi popup
    content.innerHTML = `
        <div class="detail-image-wrapper">
            <img
                src="${data.image}"
                alt="${data.title}"
                class="detail-image"
                onerror="this.style.display='none'; this.parentElement.classList.add('image-error');"
            >
        </div>

        <div class="detail-description">

            <span class="detail-label">
                ${data.label}
            </span>

            <div class="detail-text">
                ${data.content}
            </div>

        </div>
    `;

    // Buka modal
    modal.classList.add("active");

    document.body.classList.add("modal-open");

    // Kunci scroll halaman
    document.body.style.overflow = "hidden";
}


/* ================= CLOSE DETAIL ================= */

function closeDetail() {

    const modal = document.getElementById("detailModal");

    if (!modal) return;

    modal.classList.remove("active");

    document.body.classList.remove("modal-open");

    document.body.style.overflow = "";
}


/* ================= ESC CLOSE ================= */

document.addEventListener("keydown", function (event) {

    if (event.key === "Escape") {
        closeDetail();
    }

});


/* ================= CLICK OUTSIDE MODAL ================= */

document.addEventListener("click", function (event) {

    const modal = document.getElementById("detailModal");

    if (!modal) return;

    const overlay = modal.querySelector(".modal-overlay");

    if (event.target === overlay) {
        closeDetail();
    }

});


/* ================= MAKE FUNCTION GLOBAL ================= */
/* Ini penting karena HTML kamu memakai onclick="openDetail(...)" */

window.openDetail = openDetail;
window.closeDetail = closeDetail;